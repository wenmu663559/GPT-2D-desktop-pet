const { contextBridge, ipcRenderer } = require('electron');
const listen = (channel, callback) => { const handler = (_event, value) => callback(value); ipcRenderer.on(channel, handler); return () => ipcRenderer.removeListener(channel, handler); };
contextBridge.exposeInMainWorld('desktop', {
  settings: () => ipcRenderer.invoke('get-settings'),
  motionFields: () => ipcRenderer.invoke('motion-fields'),
  preference: (key, value) => ipcRenderer.send('preference', key, value),
  scale: value => ipcRenderer.send('scale', value),
  menu: () => ipcRenderer.send('menu'),
  controls: surface => ipcRenderer.send('controls', surface),
  performAction: action => ipcRenderer.send('perform-action', action),
  reportState: state => ipcRenderer.send('pet-state', state),
  ignore: value => ipcRenderer.send('ignore', value),
  hide: () => ipcRenderer.send('hide'),
  quit: () => ipcRenderer.send('quit'),
  interactive: value => ipcRenderer.send('interactive', value),
  dragStart: () => ipcRenderer.send('drag-start'),
  dragEnd: () => ipcRenderer.send('drag-end'),
  wander: direction => ipcRenderer.send('wander', direction),
  chatConfig: () => ipcRenderer.invoke('chat-config'),
  saveKey: key => ipcRenderer.invoke('chat-key', key),
  clearKey: () => ipcRenderer.invoke('chat-clear-key'),
  chat: text => ipcRenderer.invoke('chat-send', text),
  cancelChat: () => ipcRenderer.send('chat-cancel'),
  resetChat: () => ipcRenderer.send('chat-reset'),
  keyPage: () => ipcRenderer.send('open-key-page'),
  ready: () => ipcRenderer.send('renderer-ready'),
  onAction: callback => listen('action', callback),
  onSettings: callback => listen('settings', callback),
  onCursor: callback => listen('cursor', callback),
  onNotice: callback => listen('notice', callback),
  onSurface: callback => listen('surface', callback),
  onControlsVisible: callback => listen('controls-visible', callback),
  onPetState: callback => listen('pet-state', callback)
});
